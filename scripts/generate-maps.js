// scripts/generate-maps.js
//
// Draws the travel maps on the About page from places.json:
//   partials/map-world.hbs     – every place Kristy has been, as a dot
//   partials/map-roadtrip.hbs  – the US road trip as a route
//
// The maps are plain inline SVG, drawn once at build time, so the page
// needs no map library or JavaScript in the browser. The coastlines come
// from Natural Earth (public domain) via the world-atlas package.
//
// To add a place: add it to places.json (name, country, lat, lon).
// The world map zooms itself to fit all places, so nothing else changes.
// Run with: npm run generate (dev and build already do this).

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
import { geoNaturalEarth1, geoConicConformal, geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const { places, roadTrip } = JSON.parse(readFileSync(resolve(ROOT, 'places.json'), 'utf-8'));
// Two levels of detail: the coarse one keeps the world map small, the
// detailed one makes the coastline of the zoomed-in road trip map look right.
function loadAtlas(file) {
  const atlas = require(`world-atlas/${file}`);
  return {
    land: feature(atlas, atlas.objects.land),
    borders: mesh(atlas, atlas.objects.countries, (a, b) => a !== b),
  };
}
const coarse = loadAtlas('countries-110m.json');
const detailed = loadAtlas('countries-50m.json');

const round = (n) => Math.round(n * 10) / 10;
const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

// A rectangle (as a line around its edge) used to zoom a projection to an
// area. Points along the edges keep the fit correct on curved projections.
function boundsOutline([west, south, east, north]) {
  const points = [];
  for (let i = 0; i <= 20; i++) {
    const t = i / 20;
    points.push([west + (east - west) * t, south]);
    points.push([west + (east - west) * t, north]);
    points.push([west, south + (north - south) * t]);
    points.push([east, south + (north - south) * t]);
  }
  return { type: 'MultiPoint', coordinates: points };
}

// Area that contains all given points, plus some breathing room.
function boundsOf(points, padding) {
  const lons = points.map((p) => p.lon);
  const lats = points.map((p) => p.lat);
  return [
    Math.min(...lons) - padding,
    Math.min(...lats) - padding,
    Math.max(...lons) + padding,
    Math.max(...lats) + padding,
  ];
}

// Shared drawing: background, land and borders, clipped to the viewBox.
function baseLayers(projection, width, height, { land, borders }) {
  projection.clipExtent([[-10, -10], [width + 10, height + 10]]);
  const path = geoPath(projection).digits(1);
  return `
  <rect class="map__sea" width="${width}" height="${height}" />
  <path class="map__land" d="${path(land)}" />
  <path class="map__borders" d="${path(borders)}" />`;
}

function pin(projection, place, className, extraLabel = '', radius = 5) {
  const [x, y] = projection([place.lon, place.lat]);
  const label = escape(extraLabel ? `${place.name}, ${extraLabel}` : place.name);
  return `
  <g class="${className}" tabindex="0" role="img" aria-label="${label}" transform="translate(${round(x)} ${round(y)})">
    <title>${label}</title>
    <circle class="map__pin-halo" r="${radius * 2.2}" />
    <circle r="${radius}" />
  </g>`;
}

// ---------------------------------------------------------------------------
// World map
// ---------------------------------------------------------------------------
function worldMap() {
  const width = 960;
  const height = 520;
  const area = boundsOf(places, 8);
  const centerLon = (area[0] + area[2]) / 2;

  const projection = geoNaturalEarth1()
    .rotate([-centerLon, 0])
    .fitExtent([[0, 0], [width, height]], boundsOutline(area));

  const pins = places.map((place) => pin(projection, place, 'map__pin', place.country)).join('');

  return `{{!-- Generated by scripts/generate-maps.js from places.json. Do not edit. --}}
<svg class="map map--world" viewBox="0 0 ${width} ${height}" role="group"
     aria-label="World map with the places I have visited" xmlns="http://www.w3.org/2000/svg">
  ${baseLayers(projection, width, height, coarse)}
  ${pins}
</svg>
`;
}

// ---------------------------------------------------------------------------
// Road trip map
// ---------------------------------------------------------------------------
function roadTripMap() {
  const width = 720;
  const height = 760;
  const all = [...roadTrip.stops, ...roadTrip.sights];
  const area = boundsOf(all, 1.5);

  const projection = geoConicConformal()
    .parallels([33, 45])
    .rotate([-(area[0] + area[2]) / 2, 0])
    .fitExtent([[0, 0], [width, height]], boundsOutline(area));

  const routePath = geoPath(projection).digits(1)({
    type: 'LineString',
    coordinates: roadTrip.stops.map((stop) => [stop.lon, stop.lat]),
  });

  // The route starts and ends in the same place, so skip the duplicate.
  const uniqueStops = roadTrip.stops.filter(
    (stop, i, list) => list.findIndex((other) => other.name === stop.name) === i
  );

  const stops = uniqueStops.map((stop) => pin(projection, stop, 'map__pin map__pin--stop', 'stop along the route')).join('');

  // Sights are drawn as small diamonds with a name. "label" in places.json
  // (left, right, above or below; default right) moves a name that would
  // otherwise overlap a neighbour.
  const labelOffsets = {
    right: { x: 9, y: 5, anchor: 'start' },
    left: { x: -9, y: 5, anchor: 'end' },
    above: { x: 0, y: -10, anchor: 'middle' },
    below: { x: 0, y: 20, anchor: 'middle' },
  };
  const sightPoint = (sight) => projection([sight.lon, sight.lat]).map(round);

  const sightMarkers = roadTrip.sights.map((sight) => {
    const [x, y] = sightPoint(sight);
    return `
  <path class="map__sight" transform="translate(${x} ${y})" d="M0 -6 L6 0 L0 6 L-6 0 Z" />`;
  }).join('');

  // Names go in their own layer on top, so dots never cover them.
  const sightLabels = roadTrip.sights.map((sight) => {
    const [x, y] = sightPoint(sight);
    const offset = labelOffsets[sight.label] || labelOffsets.right;
    return `
  <text class="map__label" x="${x + offset.x}" y="${y + offset.y}" text-anchor="${offset.anchor}">${escape(sight.name)}</text>`;
  }).join('');

  return `{{!-- Generated by scripts/generate-maps.js from places.json. Do not edit. --}}
<svg class="map map--roadtrip" viewBox="0 0 ${width} ${height}" role="group"
     aria-label="Map of the road trip route through the American West" xmlns="http://www.w3.org/2000/svg">
  ${baseLayers(projection, width, height, detailed)}
  <path class="map__route" d="${routePath}" />
  ${sightMarkers}
  ${stops}
  ${sightLabels}
</svg>
`;
}

writeFileSync(resolve(ROOT, 'partials/map-world.hbs'), worldMap());
writeFileSync(resolve(ROOT, 'partials/map-roadtrip.hbs'), roadTripMap());
console.log(`Maps generated: ${places.length} places, ${roadTrip.stops.length - 1} road trip stops.`);
